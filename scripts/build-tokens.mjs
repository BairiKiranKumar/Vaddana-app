// Generates app/tokens.css from design/tokens.json (DTCG 2025.10).
// Core values become plain :root variables (--core-*). Everything else becomes a Tailwind @theme
// variable, and Tailwind's default palette, type, radius, shadow and tracking scales are reset,
// so the only utilities that exist are token utilities (bg-paper, text-ink-muted, rounded-control…).
// Run: npm run tokens
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "design/tokens.json";
const OUT = "app/tokens.css";

// Families self-hosted by next/font (lib/fonts.ts sets these variables on <html>).
const WEB_FONTS = {
  "Noto Sans Telugu": "--ff-noto-sans-telugu",
  Ramabhadra: "--ff-ramabhadra",
};
const GENERIC = new Set(["system-ui", "sans-serif", "serif", "monospace", "-apple-system"]);

const tokens = JSON.parse(readFileSync(SRC, "utf8"));
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const flat = new Map();
(function walk(node, path, type) {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$") || typeof child !== "object" || child === null) continue;
    const t = child.$type ?? type;
    if ("$value" in child) flat.set([...path, key].join("."), { path: [...path, key], type: t, value: child.$value });
    else walk(child, [...path, key], t);
  }
})(tokens, [], tokens.$type);

// Token path -> CSS variable name.
function varName(path) {
  const [tier, group, ...rest] = path;
  if (tier === "core" && group === "color") return `--core-${kebab(rest.join("-"))}`;
  if (tier === "semantic" && group === "color") return `--color-${kebab(rest.join("-"))}`;
  const key = [group, rest[0]].join(".");
  const tail = kebab(rest.slice(key.startsWith("font.") || key.startsWith("motion.") ? 1 : 0).join("-"));
  const prefix = {
    "font.family": "font",
    "font.weight": "font-weight",
    "font.size": "text",
    "font.lineHeight": "leading",
    "font.measure": "container-measure",
    "motion.duration": "duration",
    "motion.ease": "ease",
  }[key] ?? { space: "space", size: "spacing", radius: "radius", shadow: "shadow" }[group];
  if (!prefix) throw new Error(`No CSS mapping for ${path.join(".")}`);
  return tail ? `--${prefix}-${tail}` : `--${prefix}`;
}

const dim = (v) => `${v.value}${v.unit}`;
function color(v) {
  const [r, g, b] = v.components.map((c) => Math.round(c * 255));
  return v.alpha === undefined || v.alpha === 1 ? v.hex.toLowerCase() : `rgb(${r} ${g} ${b} / ${v.alpha})`;
}

function cssValue({ path, type, value }) {
  const alias = typeof value === "string" && value.match(/^\{(.+)\}$/);
  if (alias) {
    const target = flat.get(alias[1]);
    if (!target) throw new Error(`${path.join(".")}: broken alias ${value}`);
    return `var(${varName(target.path)})`;
  }
  switch (type) {
    case "color": return color(value);
    case "dimension": return dim(value);
    case "duration": return dim(value);
    case "cubicBezier": return `cubic-bezier(${value.join(", ")})`;
    case "fontWeight": return String(value);
    case "number": return path.at(-1) === "measure" ? `${value}ch` : String(value);
    case "fontFamily":
      return value
        .map((f) => (WEB_FONTS[f] ? `var(${WEB_FONTS[f]}, "${f}")` : GENERIC.has(f) ? f : `"${f}"`))
        .join(", ");
    case "shadow":
      return `${dim(value.offsetX)} ${dim(value.offsetY)} ${dim(value.blur)} ${dim(value.spread)} ${color(value.color)}`;
    default: throw new Error(`${path.join(".")}: unsupported type ${type}`);
  }
}

const root = [];
const theme = [];
for (const token of flat.values()) {
  const line = `  ${varName(token.path)}: ${cssValue(token)};`;
  (token.path[0] === "core" && token.path[1] === "color" ? root : theme).push(line);
}
// Tailwind's numeric spacing utilities (p-4, gap-6…) multiply --spacing, so pin it to the 4px base step.
theme.push(`  --spacing: var(--space-1);`);

const css = `/* Generated by scripts/build-tokens.mjs from ${SRC}. Do not edit; run \`npm run tokens\`. */

:root {
${root.join("\n")}
}

@theme {
  --color-*: initial;
  --font-*: initial;
  --font-weight-*: initial;
  --text-*: initial;
  --leading-*: initial;
  --tracking-*: initial;
  --radius-*: initial;
  --shadow-*: initial;
  --inset-shadow-*: initial;
  --drop-shadow-*: initial;
  --ease-*: initial;
${theme.join("\n")}
}
`;
writeFileSync(OUT, css);
console.log(`${OUT}: ${root.length} core + ${theme.length} theme variables`);
